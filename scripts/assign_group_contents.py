def pick_cast(members, rng):
    """대사에 등장할 멤버 5명(또는 그 이하)을 선택."""
    if len(members) <= 5:
        return list(members)
    return rng.sample(members, 5)


def substitute_members(text, cast):
    """cast(대사 등장 멤버 리스트)로 {멤버N} 치환. 4인은 {멤버5} → {멤버1} 매핑."""
    result = text
    n = len(cast)

    if n == 4:
        # 4인 그룹: {멤버5} → {멤버1}
        result = result.replace("{멤버5}", "{멤버1}")
        # 인원수 표현 수정
        result = result.replace("다섯이서", "넷이서")
        result = result.replace("5명이서", "4명이서")
        # "세 명은 여전히 자전거" → "두 명은 여전히 자전거"
        result = result.replace("세 명은 여전히 자전거", "두 명은 여전히 자전거")

    for i, name in enumerate(cast[:5]):
        result = result.replace(f"{{멤버{i+1}}}", name)

    # "전원:" → 실제 멤버 이름
    result = result.replace("전원:", "전원:")

    return result


def make_gender_neutral(text, members):
    """성별이 드러나는 표현 제거/중립화."""
    result = text

    # 1. "NAME 형" / "NAME 언니" → "NAME"
    for name in members:
        result = result.replace(f"{name} 형", name)
        result = result.replace(f"{name} 언니", name)

    # 2. "형들" / "언니들" → "다들" or "여러분"
    result = result.replace("형들", "다들")
    result = result.replace("언니들", "다들")

    # 3. Standalone "형" in various positions
    # "형이" → remove (handles "빠른 형이" etc.)
    result = re.sub(r'\s형이', '', result)
    # "미안해 형" → "미안해"
    result = re.sub(r'(\s)형(!)', r'\1\2', result)
    result = re.sub(r'(\s)형(\.\.\.)', r'\1\2', result)
    # "형," → ","
    result = re.sub(r'\s형,', ',', result)
    # "형은" → ""
    result = re.sub(r'\s형은\s', ' ', result)
    # Standalone "형 " at start of speech (after ": ")
    result = re.sub(r'(:\s*)형\s', r'\1', result)
    # "형도요" → "그래요"
    result = result.replace("형도요", "그래요")

    # 4. "언니" standalone - same as 형
    result = re.sub(r'\s언니(!)', r'\1', result)
    result = re.sub(r'\s언니(\.\.\.)', r'\1', result)
    result = re.sub(r'\s언니,', ',', result)
    result = re.sub(r'(:\s*)언니\s', r'\1', result)

    # 5. "전 여친/남친" → "전 연인"
    result = result.replace("전 여친/남친", "전 연인")
    result = result.replace("내 전 여친", "내 전 연인")
    result = result.replace("내 전 남친", "내 전 연인")

    # 6. Clean up double spaces
    result = re.sub(r'  +', ' ', result)
    # Clean up trailing spaces on lines
    result = re.sub(r' +\n', '\n', result)

    return result


def parse_script(text):
    """스크립트 텍스트를 구조화된 씬/대사 리스트로 파싱."""
    scenes = []
    current_scene = None
    current_lines = []

    for raw_line in text.strip().split('\n'):
        line = raw_line.strip()
        if not line:
            continue

        # Scene header: [...]
        if line.startswith('[') and line.endswith(']'):
            if current_scene is not None:
                scenes.append({"scene": current_scene, "lines": current_lines})
            current_scene = line[1:-1]
            current_lines = []
        # Stage direction: (...)
        elif line.startswith('(') and ':' not in line.split(')')[0]:
            current_lines.append({"type": "direction", "text": line})
        # Dialogue: SPEAKER: text
        elif ':' in line:
            colon_idx = line.index(':')
            speaker = line[:colon_idx].strip()
            dialogue = line[colon_idx+1:].strip()
            current_lines.append({"type": "dialogue", "speaker": speaker, "text": dialogue})
        # Plain text (narration/mission card)
        else:
            current_lines.append({"type": "narration", "text": line})

    if current_scene is not None:
        scenes.append({"scene": current_scene, "lines": current_lines})

    return scenes


