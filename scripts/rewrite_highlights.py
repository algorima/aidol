from pathlib import Path

DATA_PATH = Path(__file__).parent / "output" / "group_highlights.json"

D = "dialogue"
DR = "direction"
N = "narration"

def line(type_: str, text: str, speaker: str = "") -> dict:
    d = {"type": type_, "text": text}
    if speaker:
        d["speaker"] = speaker
    return d

def dl(speaker: str, text: str) -> dict:
    return line(D, text, speaker)

def dr(text: str) -> dict:
    return line(DR, text)

def nr(text: str) -> dict:
    return line(N, text)


