def main():
    with open(DATA_PATH, encoding="utf-8") as f:
        groups = json.load(f)

    updated = 0
    for group in groups:
        gname = group["group_name"]
        for hl in group["highlights"]:
            key = (gname, hl["content_id"])
            if key in NEW_CONTENT:
                new = NEW_CONTENT[key]
                hl["scenes"] = new["scenes"]
                updated += 1
                lines = sum(len(s["lines"]) for s in new["scenes"])
                print(f"  [{gname:8s}] {hl['title']:20s} -> {lines}줄")

    print(f"\n총 {updated}/40개 하이라이트 업데이트")

    with open(DATA_PATH, "w", encoding="utf-8") as f:
        json.dump(groups, f, indent=2, ensure_ascii=False)
    print(f"저장: {DATA_PATH}")


if __name__ == "__main__":
    main()
